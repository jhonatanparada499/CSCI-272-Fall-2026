// What is Big-O Notation?
//
// Answer: It's a standard way to "determine" the efficiency of an algorithm in
// terms of time-complexity. It's rather a representation (like the infinite
// symbol in math) than a precise numeric value.
//
// Why is Big-O important for programmers?
//
// Answer: Because it can help you make programs run faster. In real life, it
// could be translated into saving time. An inefficient example would be to call
// attendance twice(O(n^2)) compared to only once(O(n)).
//
// Why was vector a better choice than array for this problem?
//
// Answer: Because vectors are resizeable compared to the static nature of
// arrays. If dishes were to be added or removed, an array could not accommodate
// for new dishes like a vector would.
